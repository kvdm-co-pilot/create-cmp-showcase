package com.kvdm.fuelled.data.local

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor

@Database(
    entities = [FoodEntity::class, TodayGoalEntity::class, LogEntryEntity::class, SupplementEntity::class, ProfileEntity::class],
    version = 6,
    exportSchema = true,
)
@ConstructedBy(AppDatabaseConstructor::class)
abstract class AppDatabase : RoomDatabase() {
    abstract fun foodDao(): FoodDao
    abstract fun todayDao(): TodayDao
    abstract fun supplementDao(): SupplementDao
    abstract fun profileDao(): ProfileDao
}

// The actual implementation is generated by Room's KSP processor per platform.
@Suppress("NO_ACTUAL_FOR_EXPECT", "KotlinNoActualForExpect")
expect object AppDatabaseConstructor : RoomDatabaseConstructor<AppDatabase> {
    override fun initialize(): AppDatabase
}
